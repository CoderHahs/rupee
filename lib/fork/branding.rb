# frozen_string_literal: true

require "yaml"

# Upstream's English strings name the app "Sure". Rather than edit ~30 upstream
# locale files, the fork writes overrides for each such string to one file that
# loads after config/locales. Regenerate it with `bin/rails fork:locales`.
module Fork
  module Branding
    UPSTREAM_NAME = /\bSure\b/
    OVERRIDES_PATH = "config/fork/locales/en.yml"

    # Keys where "Sure" names the upstream project or its export format, not this app.
    KEEP_KEYS = %w[
      en.imports.type_labels.sure_import
      en.imports.table.row.type_labels.sure_import
      en.imports.new.import_sure
      en.imports.ready.missing_merchant_warning_description.one
      en.imports.ready.missing_merchant_warning_description.other
      en.sure_import.preflight.skipped_missing_merchant_reference
      en.subscriptions.upgrade.contribute_and_support_sure
      en.subscriptions.upgrade.header.sure
    ].freeze

    HEADER = <<~YAML
      # Generated by `bin/rails fork:locales` from lib/fork/branding.rb. Do not edit.
      # English strings from config/locales where "Sure" names this app.
    YAML

    module_function

    # Every English string in config/locales that names Sure, keyed by its full dotted path.
    def upstream_strings(root)
      found = {}
      Dir[File.join(root, "config/locales/**/en.yml")].sort.each do |file|
        collect(YAML.safe_load_file(file, aliases: true, permitted_classes: [ Symbol ]), [], found)
      end
      found
    end

    def renamed_strings(root, product_name)
      upstream_strings(root).except(*KEEP_KEYS).transform_values { |value| value.gsub(UPSTREAM_NAME, product_name) }
    end

    def render(root, product_name)
      tree = {}
      renamed_strings(root, product_name).each do |key, value|
        *parents, leaf = key.split(".")
        parents.reduce(tree) { |node, part| node[part] ||= {} }[leaf] = value
      end
      HEADER + tree.to_yaml(line_width: -1).delete_prefix("---\n")
    end

    def collect(node, path, found)
      case node
      when Hash then node.each { |key, value| collect(value, path + [ key.to_s ], found) }
      when String then found[path.join(".")] = node if node.match?(UPSTREAM_NAME)
      end
    end
  end
end
